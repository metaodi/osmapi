"""
HTTP session management for the OpenStreetMap API.
"""

import datetime
import email.utils
import itertools as it
import logging
import requests
import time
from typing import Any

from . import errors

logger = logging.getLogger(__name__)

ERROR_BY_STATUS: dict[int, type[errors.ApiError]] = {
    401: errors.UnauthorizedApiError,
    404: errors.ElementNotFoundApiError,
    410: errors.ElementDeletedApiError,
    429: errors.RateLimitApiError,
    500: errors.InternalServerApiError,
    502: errors.BadGatewayApiError,
    503: errors.ServiceUnavailableApiError,
    504: errors.GatewayTimeoutApiError,
    509: errors.RateLimitApiError,
}
"""
Error class raised for a given HTTP status code.

Any other status >= 500 becomes a generic `OsmApi.ServerApiError`, anything
else a plain `OsmApi.ApiError`. Note that 509 (bandwidth limit exceeded) is a
rate limit rather than a server failure, hence it is not a `ServerApiError`.
"""

RETRY_ON = (errors.ServerApiError, errors.RateLimitApiError)
"""
Errors that make `OsmApiSession._http` try the request again.

This is osmapi's own retry policy, which is narrower than
`OsmApi.RetriableApiError`: a timeout or a connection error is worth
retrying for a caller, but retrying it here would block for several times the
configured timeout before reporting a server that is simply unreachable.
"""


def _parse_retry_after(value: str | None) -> float | None:
    """
    Convert a `Retry-After` header into a number of seconds.

    The header comes either as delay-seconds (`"120"`) or as an HTTP-date
    (`"Wed, 21 Oct 2015 07:28:00 GMT"`), see RFC 9110. Returns `None` if the
    header is missing or cannot be parsed, and never returns a negative delay
    (a date in the past means "retry now").
    """
    if value is None:
        return None
    value = value.strip()
    # RFC 9110 defines delay-seconds as digits only; parsing this with float()
    # would also accept "inf" and "nan", which `time.sleep` chokes on
    if value.isdigit():
        return float(value)
    try:
        retry_at = email.utils.parsedate_to_datetime(value)
    except (TypeError, ValueError):
        return None
    if retry_at.tzinfo is None:
        retry_at = retry_at.replace(tzinfo=datetime.timezone.utc)
    now = datetime.datetime.now(datetime.timezone.utc)
    return max((retry_at - now).total_seconds(), 0)


class OsmApiSession:
    MAX_RETRY_LIMIT = 5
    """Maximum retries if a call to the remote API fails (default: 5)"""

    RETRY_BASE_DELAY = 5
    """Seconds to wait before the second attempt, doubling for each further one"""

    MAX_RETRY_DELAY = 60
    """Upper bound for the wait between two attempts, including `Retry-After`"""

    def __init__(
        self,
        base_url: str,
        created_by: str,
        session: requests.Session | None = None,
        timeout: int = 30,
    ) -> None:
        self._api = base_url
        self._created_by = created_by
        self._timeout = timeout

        # authentication is taken from the session (e.g. an OAuth 2.0 session)
        self._auth: Any = getattr(session, "auth", None)

        # A caller-provided session can carry credentials in ways that are not
        # visible from the outside: `session.auth`, an `Authorization` header,
        # a custom transport adapter, or a `Session` subclass adding the token
        # per request (this is what requests-oauthlib does). Sniffing
        # `session.auth` therefore both rejects valid setups and accepts
        # sessions without any token, so it is not used to make this decision:
        # the only case in which authentication is certainly missing is a
        # session that was built here, i.e. one the caller didn't provide.
        # Everything else is sent, and the API answers with a 401 ->
        # `UnauthorizedApiError` if the authorization really was missing.
        self._can_authenticate: bool = session is not None

        self._http_session = session
        self._session = self._get_http_session()

    def close(self) -> None:
        if self._session:
            self._session.close()

    def _http_request(  # noqa: C901
        self,
        method: str,
        path: str,
        auth: bool,
        send: str | bytes | None,
        return_value: bool = True,
        params: dict | None = None,
    ) -> bytes:
        """
        Returns the response generated by an HTTP request.

        `method` is a HTTP method to be executed
        with the request data. For example: 'GET' or 'POST'.
        `path` is the path to the requested resource relative to the
        base API address stored in self._api. Should start with a
        slash character to separate the URL.
        `auth` is a boolean indicating whether authentication should
        be preformed on this request.
        `send` contains additional data that might be sent in a
        request.
        `return_value` indicates wheter this request should return
        any data or not.

        If the request requires authentication and no session was provided to
        carry credentials, `OsmApi.AuthenticationMissingError` is raised. With
        a session, the request is sent and a rejected authorization surfaces
        as `OsmApi.UnauthorizedApiError` (HTTP 401).

        If the requested element has been deleted,
        `OsmApi.ElementDeletedApiError` is raised.

        If the requested element can not be found,
        `OsmApi.ElementNotFoundApiError` is raised.

        If the API failed to handle the request (HTTP 5xx),
        `OsmApi.ServerApiError` (or one of its subclasses) is raised.

        If the API refused the request because a limit was exceeded,
        `OsmApi.RateLimitApiError` is raised.

        If the response status code indicates any other error,
        `OsmApi.ApiError` is raised.
        """
        logger.debug(f"{datetime.datetime.now():%Y-%m-%d %H:%M:%S} {method} {path}")

        # Add API base URL to path
        path = self._api + path

        if auth and not self._can_authenticate:
            raise errors.AuthenticationMissingError(
                "Authentication missing, this request requires an "
                "authenticated session, but no session was provided "
                "(see the OAuth 2.0 examples)"
            )

        try:
            response = self._session.request(
                method, path, data=send, timeout=self._timeout, params=params
            )
        except requests.exceptions.Timeout as e:
            raise errors.TimeoutApiError(
                0, f"Request timed out (timeout={self._timeout})", ""
            ) from e
        except requests.exceptions.ConnectionError as e:
            raise errors.ConnectionApiError(0, f"Connection error: {str(e)}", "") from e
        except requests.exceptions.RequestException as e:
            raise errors.ApiError(0, str(e), "") from e

        if response.status_code != 200:
            payload = response.content.strip()
            error_class = ERROR_BY_STATUS.get(response.status_code)
            if error_class is None:
                error_class = (
                    errors.ServerApiError
                    if response.status_code >= 500
                    else errors.ApiError
                )
            raise error_class(
                response.status_code,
                response.reason,
                payload,
                retry_after=_parse_retry_after(response.headers.get("Retry-After")),
            )
        if return_value and not response.content:
            raise errors.ResponseEmptyApiError(
                response.status_code, response.reason, ""
            )

        logger.debug(f"{datetime.datetime.now():%Y-%m-%d %H:%M:%S} {method} {path}")
        return response.content

    def _http(  # type: ignore[return-value]  # noqa: C901
        self,
        cmd: str,
        path: str,
        auth: bool,
        send: str | bytes | None,
        return_value: bool = True,
        params: dict | None = None,
    ) -> bytes:
        for i in it.count(1):
            try:
                return self._http_request(
                    cmd, path, auth, send, return_value=return_value, params=params
                )
            except errors.ApiError as e:
                if isinstance(e, RETRY_ON):
                    if i == self.MAX_RETRY_LIMIT:
                        raise
                    delay = self._retry_delay(i, e.retry_after)
                    if delay:
                        self._sleep(delay)
                    self._session = self._get_http_session()
                else:
                    logger.debug("ApiError Exception occured")
                    raise
            except errors.AuthenticationMissingError:
                raise
            except Exception as e:
                logger.exception("General exception occured")
                if i == self.MAX_RETRY_LIMIT:
                    if isinstance(e, errors.OsmApiError):
                        raise
                    raise errors.MaximumRetryLimitReachedError(
                        f"Give up after {i} retries"
                    ) from e
                delay = self._retry_delay(i)
                if delay:
                    self._sleep(delay)
                self._session = self._get_http_session()

    def _get_http_session(self) -> requests.Session:
        """
        Creates a requests session for connection pooling.
        """
        if self._http_session:
            session = self._http_session
        else:
            session = requests.Session()

        session.auth = self._auth
        session.headers.update({"user-agent": self._created_by})
        return session

    def _retry_delay(self, attempt: int, retry_after: float | None = None) -> float:
        """
        Seconds to wait before attempt number `attempt` + 1.

        A `Retry-After` sent by the API wins over the schedule, but is capped
        at `MAX_RETRY_DELAY` — if the API asks for a longer break than that,
        the remaining attempts run into the same limit and the error is
        reported to the caller, which can wait for `ApiError.retry_after` and
        try again itself.

        Without such a header the first retry follows immediately (a single
        failed request is often just a hiccup), and every further one waits
        twice as long as the previous, starting at `RETRY_BASE_DELAY`.
        """
        if retry_after is not None:
            return min(retry_after, self.MAX_RETRY_DELAY)
        if attempt <= 1:
            return 0
        return min(self.RETRY_BASE_DELAY * 2 ** (attempt - 2), self.MAX_RETRY_DELAY)

    def _sleep(self, seconds: float = 5) -> None:
        time.sleep(seconds)

    def _get(self, path: str, params: dict | None = None) -> bytes:
        return self._http("GET", path, False, None, params=params)

    def _put(
        self, path: str, data: str | bytes | None, return_value: bool = True
    ) -> bytes:
        return self._http("PUT", path, True, data, return_value=return_value)

    def _post(
        self,
        path: str,
        data: str | bytes | None,
        optionalAuth: bool = False,
        forceAuth: bool = False,
        params: dict | None = None,
    ) -> bytes:
        # the Notes API allows certain POSTs by non-authenticated users
        auth = optionalAuth and self._can_authenticate
        if forceAuth:
            auth = True
        return self._http("POST", path, bool(auth), data, params=params)

    def _delete(self, path: str, data: str | bytes | None) -> bytes:
        return self._http("DELETE", path, True, data)
